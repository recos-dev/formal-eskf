"""Export the memory-safety harness; scripts/verify_esbmc.sh owns execution."""

import argparse
from pathlib import Path

from ins.formatting import format_cpp
from ins.verify import require
from ins.verify.product_reference import contracts

ROOT = Path(__file__).resolve().parents[3]


def source():
    TEXT = '// Generated by codegen/products.py esbmc-export; do not edit. Tag: 2026-11-18.\n\n'
    TEXT += (ROOT / 'formal/cpp/esbmc/codegen_storage.hpp').read_text().split('#pragma once')[0]
    TEXT += '#include "codegen_storage.hpp"\n'
    TEXT += '\n'.join(f'#include <formal_eskf/eskf/generated/ins_{G}.hpp>'
                      for G in ('reset', 'innovation', 'joseph')) + '\n'
    for NAME, SPEC in contracts().items():
        TEXT += f'\n#if defined(PROVE_{NAME.upper()})\nvoid verify_product_memory()\n{{\n'
        for N, (R, C) in SPEC['dimensions'].items():
            TEXT += f'    formal_eskf::linalg::Matrix<FixedArray,{R}U,{C}U> {N};\n    symbolic({N});\n'
        TEXT += f'    auto const result=formal_eskf::detail::generated::{NAME}({", ".join(SPEC["dimensions"])});\n'
        TEXT += '    (void)result;\n}\n#endif\n'
    return format_cpp(TEXT)


def main():
    PARSER = argparse.ArgumentParser(description=__doc__)
    PARSER.add_argument('--check', action='store_true')
    ARGS = PARSER.parse_args()
    FILE = ROOT / 'formal/cpp/esbmc/codegen_products.cpp'
    TEXT = source()
    if ARGS.check:
        require(FILE.read_text() == TEXT, 'stale generated memory harness')
    else:
        FILE.write_text(TEXT)


if __name__ == '__main__':
    main()

"""Export Lean certificates from parsed C++ and the independent block reference.

Do not normalize arithmetic on the emitted-source side. Lean's ring tactic
checks its raw expression against the independently defined matrix model.
Exporting these files does not execute Lean.
"""

from pathlib import Path

import sympy as S

from .algebra import exact_model
from .cpp import parse

HEADER = '''/-
formal-eskf is freely redistributable under the BSD 3-Clause License.
See the file "LICENSE" for information on usage and redistribution of this
file.

SPDX-License-Identifier: BSD-3-Clause
-/

-- Generated by codegen/generate.py; do not edit. Tag: 2026-11-18.

'''


def lean_symbol(NAME):
    if NAME == 'delta_t':
        return 'dt'
    PREFIX, *INDICES = NAME.split('_')
    TARGET = {
        'prior': 'P', 'force': 'A', 'bias': 'B',
        'attitude': 'T', 'rotation': 'R', 'impulse': 'Q',
    }[PREFIX]
    return '(' + TARGET + ' ' + ' '.join(f'⟨{I}, by decide⟩' for I in INDICES) + ')'


def reference_expression(EXPR):
    if EXPR.is_Symbol:
        return lean_symbol(str(EXPR))
    if EXPR.is_Integer:
        return f'({EXPR} : ℝ)'
    if EXPR.is_Add or EXPR.is_Mul:
        OPERATOR = ' + ' if EXPR.is_Add else ' * '
        return '(' + OPERATOR.join(reference_expression(ARG) for ARG in EXPR.args) + ')'
    if EXPR.is_Pow:
        return '(' + reference_expression(EXPR.base) + ' ^ ' + str(EXPR.exp) + ')'
    raise ValueError(f'unsupported reference expression: {EXPR}')


def source_expression(NODE, VALUES):
    OPERATOR = NODE[0]
    if OPERATOR == 'ref':
        return VALUES[NODE[1]]
    if OPERATOR == 'int':
        return f'({NODE[1]} : ℝ)'
    if OPERATOR == 'neg':
        return '(-' + source_expression(NODE[1], VALUES) + ')'
    LEFT = source_expression(NODE[1], VALUES)
    RIGHT = source_expression(NODE[2], VALUES)
    SYMBOL = {'add': ' + ', 'sub': ' - ', 'mul': ' * '}[OPERATOR]
    return '(' + LEFT + SYMBOL + RIGHT + ')'


def matrix_definition(MATRIX):
    CASES = [
        f'| {I}, {J} => {reference_expression(MATRIX[I, J])}'
        for I in range(MATRIX.rows)
        for J in range(MATRIX.cols)
        if MATRIX[I, J] != 0
    ]
    return 'Matrix.of fun i j => match i.val, j.val with\n    ' + '\n    '.join(CASES) + '\n    | _, _ => 0'


def model_certificate(INPUTS):
    F = S.Matrix(15, 15, lambda I, J: INPUTS['F', I, J])
    G = S.zeros(15, 12)
    for I in range(3):
        for J in range(3):
            G[I + 3, J] = -INPUTS['R', I, J]
        G[I + 6, I + 3] = -1
        G[I + 9, I + 6] = 1
        G[I + 12, I + 9] = 1
    TEXT = '''import FormalESKF.Covariance
import Mathlib.Tactic.FinCases
import Mathlib.Tactic.Ring

namespace Codegen
noncomputable section
open Matrix
set_option maxRecDepth 4096
set_option linter.unusedVariables false
abbrev M3 := Matrix (Fin 3) (Fin 3) ℝ
abbrev M15 := Matrix (Fin 15) (Fin 15) ℝ
def upper (P : M15) : M15 := Matrix.of fun i j => if i ≤ j then P i j else P j i
def transition (dt : ℝ) (A B T : M3) : M15 :=
    ''' + matrix_definition(F) + '''
def injection (R : M3) : Matrix (Fin 15) (Fin 12) ℝ :=
    ''' + matrix_definition(G) + '''
def transported (dt : ℝ) (A B T : M3) (P : M15) : M15 :=
    transition dt A B T * upper P
def noise (R : M3) (Q : Fin 12 → ℝ) : M15 :=
    injection R * Matrix.diagonal Q * (injection R)ᵀ
def reference (dt : ℝ) (A B T R : M3) (P : M15) (Q : Fin 12 → ℝ) : M15 :=
    transported dt A B T P * (transition dt A B T)ᵀ + noise R Q
theorem noise_apply (R : M3) (Q : Fin 12 → ℝ) (i j : Fin 15) :
    noise R Q i j = ∑ k : Fin 12, injection R i k * Q k * injection R j k := by
  rw [noise, Matrix.mul_apply]
  simp only [Matrix.mul_diagonal, Matrix.transpose_apply]
'''
    for I in range(15):
        VALUE = ' + '.join(
            f'{reference_expression(F[I, K])} * upper P ⟨{K}, by decide⟩ j'
            for K in range(15) if F[I, K] != 0
        )
        TEXT += f'''theorem transported_row_{I} (dt : ℝ) (A B T : M3) (P : M15) (j : Fin 15) :
    transported dt A B T P ⟨{I}, by decide⟩ j = {VALUE} := by
  rw [transported, Matrix.mul_apply]
  simp only [Fin.sum_univ_succ]
  norm_num [transition, Matrix.of_apply, Fin.succ, add_assoc]
'''
    TEXT += '''
/-- Shared normalization for generated entries; ring checks every remaining identity. -/
macro "codegen_covariance" : tactic =>
  `(tactic| (norm_num [transition, injection, upper, Matrix.of_apply, Fin.succ]
    <;> norm_num only [Fin.le_def, Fin.val_ofNat, Fin.val_zero, Fin.val_one, ite_false, ite_true]
    <;> ring))
'''
    return TEXT + 'end\nend Codegen\n'


def source_entries(PROGRAM, INPUTS):
    VALUES = {KEY: reference_expression(VALUE) for KEY, VALUE in INPUTS.items()}
    ENTRIES = []
    for NAME, NODE in PROGRAM:
        VALUES[NAME] = source_expression(NODE, VALUES)
        if isinstance(NAME, tuple) and NAME[1] <= NAME[2]:
            I, J = NAME[1:]
            ENTRIES.append((I, J, VALUES[NAME]))
    return ENTRIES


def row_certificate(ROW, ENTRIES):
    LINES = [
        'import FormalESKF.codegen.Model\n\nnamespace Codegen\nnoncomputable section\nopen Matrix\n'
        'set_option maxHeartbeats 4000000\nset_option maxRecDepth 4096\n'
        'set_option linter.unusedVariables false\n'
    ]
    for I, J, EXPR in ENTRIES:
        if I != ROW:
            continue
        LINES.append(f'''def generated_{I}_{J} (dt : ℝ) (A B T R : M3) (P : M15) (Q : Fin 12 → ℝ) : ℝ :=
  {EXPR}
theorem entry_{I}_{J} (dt : ℝ) (A B T R : M3) (P : M15) (Q : Fin 12 → ℝ) :
  generated_{I}_{J} dt A B T R P Q = reference dt A B T R P Q ⟨{I}, by decide⟩ ⟨{J}, by decide⟩ := by
  simp only [generated_{I}_{J}, reference, Matrix.add_apply, Matrix.mul_apply,
    noise_apply, Matrix.transpose_apply]
  simp only [Fin.sum_univ_succ]
  simp only [transported_row_{I}]
  codegen_covariance
''')
    LINES.append('end\nend Codegen\n')
    return '\n'.join(LINES)


def matrix_certificate(PROGRAM):
    """Assemble all stores, following the actual lower-triangle references."""
    CALLS = {}
    for NAME, NODE in PROGRAM:
        if isinstance(NAME, tuple) and NAME[0] == 'out':
            I, J = NAME[1:]
            if I <= J:
                CALLS[I, J] = f'generated_{I}_{J} dt A B T R P Q'
            else:
                CALLS[I, J] = CALLS[NODE[1][1:]]
    ROWS = ['![' + ', '.join(CALLS[I, J] for J in range(15)) + ']' for I in range(15)]
    LINES = [f'import FormalESKF.codegen.Row{I:02d}' for I in range(15)]
    LINES += [
        '\nnamespace Codegen\nnoncomputable section\nopen Matrix\n'
        'set_option maxHeartbeats 4000000\nset_option maxRecDepth 4096\n',
        'def generatedMatrix (dt : ℝ) (A B T R : M3) (P : M15) (Q : Fin 12 → ℝ) : M15 :=\n'
        '  Matrix.of ![' + ',\n    '.join(ROWS) + ']',
        '''theorem generatedMatrix_eq_reference (dt : ℝ) (A B T R : M3) (P : M15) (Q : Fin 12 → ℝ)
    (hsym : (reference dt A B T R P Q)ᵀ = reference dt A B T R P Q) :
    generatedMatrix dt A B T R P Q = reference dt A B T R P Q := by
  ext i j
  fin_cases i <;> fin_cases j''',
    ]
    for I in range(15):
        for J in range(15):
            ENTRY = f'entry_{min(I, J)}_{max(I, J)} dt A B T R P Q'
            if I <= J:
                LINES.append(f'  · exact {ENTRY}')
            else:
                LINES.append(
                    f'  · exact ({ENTRY}).trans (congrArg '
                    f'(fun M : M15 => M ⟨{I}, by decide⟩ ⟨{J}, by decide⟩) hsym)'
                )
    LINES.append('end\nend Codegen\n')
    return '\n'.join(LINES)


def export(TEXT, OUTPUT):
    OUTPUT = Path(OUTPUT)
    INPUTS, _ = exact_model()
    PROGRAM = parse(TEXT)
    ENTRIES = source_entries(PROGRAM, INPUTS)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    (OUTPUT / 'Model.lean').write_bytes((HEADER + model_certificate(INPUTS)).encode('utf-8'))
    for ROW in range(15):
        (OUTPUT / f'Row{ROW:02d}.lean').write_bytes((HEADER + row_certificate(ROW, ENTRIES)).encode('utf-8'))
    (OUTPUT / 'Entries.lean').write_bytes((HEADER + matrix_certificate(PROGRAM)).encode('utf-8'))

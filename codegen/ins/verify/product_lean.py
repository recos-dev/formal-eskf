def symbol(EXPR):
    if EXPR.is_Symbol:
        NAME, I, J = str(EXPR).rsplit('_', 2)
        return f'({NAME} ⟨{I}, by decide⟩ ⟨{J}, by decide⟩)'
    if EXPR.is_Integer:
        return f'({EXPR} : ℝ)'
    if EXPR.is_Add or EXPR.is_Mul:
        return '(' + (' + ' if EXPR.is_Add else ' * ').join(symbol(A) for A in EXPR.args) + ')'
    if EXPR.is_Pow:
        return '(' + symbol(EXPR.base) + ' ^ ' + str(EXPR.exp) + ')'
    raise ValueError(EXPR)


def matrix(M):
    ROWS = ['![' + ', '.join(symbol(M[I, J]) for J in range(M.cols)) + ']' for I in range(M.rows)]
    return 'Matrix.of ![' + ',\n    '.join(ROWS) + ']'


def parameters(SPEC):
    return ' '.join(
        f'({N} : Matrix (Fin {R}) (Fin {C}) ℝ)' for N, (R, C) in SPEC['dimensions'].items()
    )


def arguments(SPEC):
    return ' '.join(SPEC['dimensions'])


def module_name(NAME):
    return ''.join(P.capitalize() for P in NAME.split('_'))


def model_file(SPECS):
    LINES = [
        '''import FormalESKF.Covariance
import Mathlib.Tactic.FinCases
import Mathlib.Tactic.Ring

namespace Codegen.Products
noncomputable section
open Matrix
set_option maxRecDepth 8192
set_option linter.unusedVariables false
def upper {n : ℕ} (P : Matrix (Fin n) (Fin n) ℝ) :=
  Matrix.of fun i j => if i ≤ j then P i j else P j i
theorem upper_symmetric {n : ℕ} (P : Matrix (Fin n) (Fin n) ℝ) : (upper P)ᵀ = upper P := by
  ext i j
  simp only [Matrix.transpose_apply, upper, Matrix.of_apply]
  split_ifs with hji hij hij
  · have : i = j := le_antisymm hij hji
    subst j
    rfl
  · rfl
  · rfl
  · exact False.elim (hji (le_of_not_ge hij))
theorem upper_eq_self {n : ℕ} {P : Matrix (Fin n) (Fin n) ℝ} (hP : Pᵀ = P) : upper P = P := by
  ext i j
  simp only [upper, Matrix.of_apply]
  split_ifs
  · rfl
  · exact congrArg (fun M => M i j) hP
'''
    ]
    G = S.eye(15)
    for I in range(3):
        for J in range(3):
            G[I + 6, J + 6] = S.Symbol(f'J_{I}_{J}')
    LINES.append(
        'def resetG (J : Matrix (Fin 3) (Fin 3) ℝ) : Matrix (Fin 15) (Fin 15) ℝ :=\n  ' + matrix(G)
    )
    for LAYOUT, COLS in LAYOUTS.items():
        H = S.zeros(len(COLS), 15)
        PARAM = ''
        if LAYOUT == 'body_vector':
            X, Y, Z = [S.Symbol(f'h_{I}_0') for I in range(3)]
            H[:, 6:9] = S.Matrix([[0, -Z, Y], [Z, 0, -X], [-Y, X, 0]])
            PARAM = '(h : Matrix (Fin 3) (Fin 1) ℝ)'
        else:
            for I, COL in enumerate(COLS):
                H[I, COL] = 1
        LINES.append(
            f'def H_{LAYOUT} {PARAM} : Matrix (Fin {len(COLS)}) (Fin 15) ℝ :=\n  ' + matrix(H)
        )
    for NAME, SPEC in SPECS.items():
        KIND = SPEC['kind']
        R, C = SPEC['shape']
        PARAMS = parameters(SPEC)
        ARGS = arguments(SPEC)
        H = 'H_' + str(SPEC['layout']) + (' h' if SPEC['layout'] == 'body_vector' else '')
        if KIND in ('reset', 'joseph'):
            A = (
                G
                if KIND == 'reset'
                else S.Matrix(
                    15,
                    15,
                    lambda I, J: (
                        S.Symbol(f'A_{I}_{J}')
                        if J in LAYOUTS[SPEC['layout']]
                        else S.Integer(I == J)
                    ),
                )
            )
            TRANSFORM = 'resetG J' if KIND == 'reset' else matrix(A)
            LINES.append(
                f'def transform_{NAME} {PARAMS} : Matrix (Fin 15) (Fin 15) ℝ := {TRANSFORM}'
            )
            LINES.append(
                f'def transported_{NAME} {PARAMS} : Matrix (Fin 15) (Fin 15) ℝ := transform_{NAME} {ARGS} * upper P'
            )
            for I in range(15):
                TERMS = ' + '.join(
                    f'{symbol(A[I,K])} * upper P ⟨{K}, by decide⟩ j'
                    for K in range(15)
                    if A[I, K] != 0
                )
                RAW = '0'
                for K in reversed(range(15)):
                    RAW = f'{symbol(A[I,K])} * upper P ⟨{K}, by decide⟩ j + ({RAW})'
                LINES.append(
                    f'''theorem transported_{NAME}_row_{I} {PARAMS} (j : Fin 15) :
    transported_{NAME} {ARGS} ⟨{I}, by decide⟩ j = {TERMS} := by
  rw [transported_{NAME}, Matrix.mul_apply]
  simp only [Fin.sum_univ_succ]
  change ({RAW}) = _
  ring
'''
                )
        if KIND == 'reset':
            FORMULA = f'transported_{NAME} {ARGS} * (transform_{NAME} {ARGS})ᵀ'
        elif KIND == 'cross':
            FORMULA = f'upper P * ({H})ᵀ'
        elif KIND == 'innovation':
            FORMULA = f'({H}) * C + upper V'
        else:
            FORMULA = f'transported_{NAME} {ARGS} * (transform_{NAME} {ARGS})ᵀ + K * upper V * Kᵀ'
        LINES.append(f'def ref_{NAME} {PARAMS} : Matrix (Fin {R}) (Fin {C}) ℝ :=\n  {FORMULA}')
        DEFS = (
            'resetG, '
            if KIND == 'reset'
            else ('H_' + SPEC['layout'] + ', ' if KIND != 'joseph' else '')
        )
        TRANSFORM = f'transform_{NAME}, ' if SPEC['mirror'] else ''
        LINES.append(
            f'''macro "reduce_{NAME}" : tactic =>
  `(tactic| (norm_num [{TRANSFORM}{DEFS}upper, Matrix.of_apply, Fin.succ]
    <;> norm_num only [Fin.le_def, Fin.val_ofNat, Fin.val_zero, Fin.val_one, ite_false, ite_true]
    <;> (try simp only [false_implies, true_or, or_true])
    <;> ring))
'''
        )
        if SPEC['mirror']:
            EXTRA_SIMP = ", Matrix.transpose_add" if KIND == "joseph" else ""
            LINES.append(
                f'''theorem symmetric_{NAME} {PARAMS} :
    (ref_{NAME} {ARGS})ᵀ = ref_{NAME} {ARGS} := by
  simp [ref_{NAME}, transported_{NAME}, Matrix.transpose_mul{EXTRA_SIMP}, upper_symmetric, Matrix.mul_assoc]
'''
            )
    LINES.append('end\nend Codegen.Products\n')
    return '\n'.join(LINES)


def export(NAME, SPEC, PROGRAM, HASH):
    INPUTS, _ = model(SPEC)
    VALUES = {N: symbol(E) for N, E in INPUTS.items()}
    ENTRIES = {}
    for TARGET, NODE in PROGRAM:
        VALUES[TARGET] = source_expression(NODE, VALUES)
        if isinstance(TARGET, tuple):
            ENTRIES[TARGET[1:]] = VALUES[TARGET]
    MODULE = module_name(NAME)
    PARAMS, ARGS = parameters(SPEC), arguments(SPEC)
    ROWS, COLS = SPEC['shape']
    ROW_MODULES = []
    for ROW in range(ROWS):
        ROW_MODULE = f'{MODULE}Row{ROW:02d}'
        ROW_MODULES.append(ROW_MODULE)
        LINES = [
            'import FormalESKF.codegen.products.Model\n\nnamespace Codegen.Products.' + MODULE,
            'noncomputable section\nopen Matrix\nset_option maxRecDepth 8192\n'
            'set_option maxHeartbeats 4000000\nset_option linter.unusedVariables false\n',
        ]
        for J in range(COLS):
            if SPEC['mirror'] and J < ROW:
                continue
            EXPR = ENTRIES[ROW, J]
            TRANSPORT = f'  simp only [transported_{NAME}_row_{ROW}]\n' if SPEC['mirror'] else ''
            APPLY = 'Matrix.add_apply, ' if SPEC['kind'] in ('innovation', 'joseph') else ''
            TRANSPOSE = ', Matrix.transpose_apply' if SPEC['kind'] != 'innovation' else ''
            LINES.append(
                f'''def generated_{ROW}_{J} {PARAMS} : ℝ :=
  {EXPR}
theorem entry_{ROW}_{J} {PARAMS} :
  generated_{ROW}_{J} {ARGS} = ref_{NAME} {ARGS} ⟨{ROW}, by decide⟩ ⟨{J}, by decide⟩ := by
  simp only [generated_{ROW}_{J}, ref_{NAME}, {APPLY}Matrix.mul_apply{TRANSPOSE}]
  simp only [Fin.sum_univ_succ]
{TRANSPORT}  reduce_{NAME}
'''
            )
        LINES += ['end\nend Codegen.Products.' + MODULE + '\n']
        (DEST / (ROW_MODULE + '.lean')).write_text(
            TAG + '-- C++ header SHA256: ' + HASH + '\n' + '\n'.join(LINES)
        )
    LINES = [f'import FormalESKF.codegen.products.{R}' for R in ROW_MODULES]
    LINES += [
        'namespace Codegen.Products.' + MODULE,
        'noncomputable section\nopen Matrix\nset_option maxRecDepth 8192\nset_option maxHeartbeats 4000000',
    ]
    VALUES = []
    for I in range(ROWS):
        ROW = []
        for J in range(COLS):
            A, B = (min(I, J), max(I, J)) if SPEC['mirror'] else (I, J)
            ROW.append(f'generated_{A}_{B} {ARGS}')
        VALUES.append('![' + ', '.join(ROW) + ']')
    LINES.append(
        f'def generatedMatrix {PARAMS} : Matrix (Fin {ROWS}) (Fin {COLS}) ℝ :=\n  Matrix.of !['
        + ',\n    '.join(VALUES)
        + ']'
    )
    LINES.append(
        f'''theorem generatedMatrix_eq_reference {PARAMS} :
    generatedMatrix {ARGS} = ref_{NAME} {ARGS} := by
  ext i j
  fin_cases i {";" if ROWS == 1 else "<;>"} fin_cases j'''
    )
    for I in range(ROWS):
        for J in range(COLS):
            A, B = (min(I, J), max(I, J)) if SPEC['mirror'] else (I, J)
            ENTRY = f'entry_{A}_{B} {ARGS}'
            if not SPEC['mirror'] or I <= J:
                LINES.append('  · exact ' + ENTRY)
            else:
                LINES.append(
                    f'  · exact ({ENTRY}).trans (congrArg (fun M => M ⟨{I}, by decide⟩ ⟨{J}, by decide⟩) (symmetric_{NAME} {ARGS}))'
                )
    if SPEC['mirror']:
        HYP = '(hP : P.PosSemidef)' + (' (hV : V.PosSemidef)' if SPEC['kind'] == 'joseph' else '')
        PREMISES = 'upper_eq_self (FormalESKF.ESKF.posSemidef_symmetric hP)'
        RHS = f'FormalESKF.ESKF.sandwich_posSemidef (transform_{NAME} {ARGS}) hP'
        if SPEC['kind'] == 'joseph':
            PREMISES += ', upper_eq_self (FormalESKF.ESKF.posSemidef_symmetric hV)'
            RHS = f'({RHS}).add (FormalESKF.ESKF.sandwich_posSemidef K hV)'
        LINES.append(
            f'''theorem generatedMatrix_posSemidef {PARAMS} {HYP} :
    (generatedMatrix {ARGS}).PosSemidef := by
  rw [generatedMatrix_eq_reference]
  simpa only [ref_{NAME}, transported_{NAME}, {PREMISES}, FormalESKF.ESKF.sandwich] using {RHS}
'''
        )
    LINES += ['end\nend Codegen.Products.' + MODULE + '\n']
    (DEST / (MODULE + 'Entries.lean')).write_text(TAG + '\n'.join(LINES))
    return ROW_MODULES + [MODULE + 'Entries']


def composition():
    LINES = [f'import FormalESKF.codegen.products.{module_name(N)}Entries' for N in contracts()]
    LINES += ['namespace Codegen.Products', 'noncomputable section', 'open Matrix']
    for LAYOUT, COLS in LAYOUTS.items():
        PREFIX = 'ins_' + LAYOUT
        CROSS, INNOVATION, JOSEPH = [PREFIX + '_' + K for K in ('cross', 'innovation', 'joseph')]
        C_NS, S_NS, J_NS = [module_name(N) for N in (CROSS, INNOVATION, JOSEPH)]
        M = len(COLS)
        EXTRA = ' (h : Matrix (Fin 3) (Fin 1) ℝ)' if LAYOUT == 'body_vector' else ''
        H_ARG = ' h' if EXTRA else ''
        H = 'H_' + LAYOUT + H_ARG
        LINES.append(
            f'''theorem {PREFIX}_innovation_composition
    (P : Matrix (Fin 15) (Fin 15) ℝ){EXTRA} (V : Matrix (Fin {M}) (Fin {M}) ℝ)
    (hP : Pᵀ = P) (hV : Vᵀ = V) :
    {S_NS}.generatedMatrix ({C_NS}.generatedMatrix P{H_ARG}){H_ARG} V =
      FormalESKF.ESKF.innovationCovariance P ({H}) V := by
  rw [{S_NS}.generatedMatrix_eq_reference, {C_NS}.generatedMatrix_eq_reference]
  simp only [ref_{INNOVATION}, ref_{CROSS}, upper_eq_self hP, upper_eq_self hV,
    FormalESKF.ESKF.innovationCovariance]

theorem {PREFIX}_innovation_posDef
    (P : Matrix (Fin 15) (Fin 15) ℝ){EXTRA} (V : Matrix (Fin {M}) (Fin {M}) ℝ)
    (hP : P.PosSemidef) (hV : V.PosDef) :
    ({S_NS}.generatedMatrix ({C_NS}.generatedMatrix P{H_ARG}){H_ARG} V).PosDef := by
  rw [{PREFIX}_innovation_composition P{H_ARG} V
    (FormalESKF.ESKF.posSemidef_symmetric hP)
    (FormalESKF.ESKF.posSemidef_symmetric hV.posSemidef)]
  exact FormalESKF.ESKF.innovationCovariance_posDef ({H}) hP hV

/-- The caller supplies the checked A=I-K_eff H with this observation layout. -/
theorem {PREFIX}_joseph_composition
    (P A : Matrix (Fin 15) (Fin 15) ℝ){EXTRA}
    (K : Matrix (Fin 15) (Fin {M}) ℝ) (V : Matrix (Fin {M}) (Fin {M}) ℝ)
    (hP : Pᵀ = P) (hV : Vᵀ = V)
    (hA : transform_{JOSEPH} P A K V = 1 - K * ({H})) :
    {J_NS}.generatedMatrix P A K V = FormalESKF.ESKF.josephCovariance P ({H}) V K := by
  rw [{J_NS}.generatedMatrix_eq_reference]
  simp only [ref_{JOSEPH}, transported_{JOSEPH}, upper_eq_self hP, upper_eq_self hV,
    hA, FormalESKF.ESKF.josephCovariance, FormalESKF.ESKF.sandwich]
'''
        )
    LINES += ['end', 'end Codegen.Products']
    (DEST / 'Composition.lean').write_text(TAG + '\n'.join(LINES) + '\n')


def main():
    import json

    DEST.mkdir(parents=True, exist_ok=True)
    SPECS = contracts()
    FILES = ['Model']
    SOURCES = {}
    (DEST / 'Model.lean').write_text(TAG + model_file(SPECS))
    for GROUP in ('reset', 'innovation', 'joseph'):
        FILE = ROOT / f'include/formal_eskf/eskf/generated/ins_{GROUP}.hpp'
        HASH = hashlib.sha256(FILE.read_bytes()).hexdigest()
        SOURCES[str(FILE.relative_to(ROOT))] = HASH
        for NAME, PROGRAM in parse_header(FILE.read_text(), GROUP).items():
            FILES += export(NAME, SPECS[NAME], PROGRAM, HASH)
    composition()
    FILES.append('Composition')
    INVENTORY = ROOT / 'output/codegen/products/lean-inventory.json'
    INVENTORY.parent.mkdir(parents=True, exist_ok=True)
    INVENTORY.write_text(
        json.dumps({'modules': FILES, 'headers': SOURCES}, indent=2) + '\n'
    )
    print('Exported', len(FILES), 'Lean modules; not yet executed')


if __name__ == '__main__':
    main()

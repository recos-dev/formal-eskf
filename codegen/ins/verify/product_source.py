def expression(NODE, DIMENSIONS):
    if isinstance(NODE, ast.Name):
        require(re.fullmatch('[a-z][a-z0-9_]*', NODE.id) is not None, 'invalid scalar name')
        return ('ref', NODE.id)
    if isinstance(NODE, ast.Constant) and type(NODE.value) is int:
        require(NODE.value in (0, 1, 2), 'unsupported scalar integer')
        return ('int', NODE.value)
    if isinstance(NODE, ast.UnaryOp) and isinstance(NODE.op, ast.USub):
        return ('neg', expression(NODE.operand, DIMENSIONS))
    if isinstance(NODE, ast.Call) and isinstance(NODE.func, ast.Name):
        NAME = NODE.func.id
        require(
            NAME in DIMENSIONS and len(NODE.args) == 2 and not NODE.keywords, 'invalid matrix call'
        )
        require(
            all(isinstance(A, ast.Constant) and type(A.value) is int for A in NODE.args),
            'invalid index',
        )
        I, J = [A.value for A in NODE.args]
        R, C = DIMENSIONS[NAME]
        require(0 <= I < R and 0 <= J < C, 'out-of-bounds matrix access')
        return ('ref', ('out' if NAME == 'result' else NAME, I, J))
    if isinstance(NODE, ast.BinOp) and type(NODE.op) in (ast.Add, ast.Sub, ast.Mult):
        return (
            {ast.Add: 'add', ast.Sub: 'sub', ast.Mult: 'mul'}[type(NODE.op)],
            expression(NODE.left, DIMENSIONS),
            expression(NODE.right, DIMENSIONS),
        )
    raise ValueError('unsupported scalar expression')


def parse_function(SOURCE, NAME, SPEC):
    R, C = SPEC['shape']
    PARAMETERS = ', '.join(
        f'linalg::Matrix<Linalg, {I}U, {J}U> const & {M}'
        for M, (I, J) in SPEC['dimensions'].items()
    )
    PREFIX = tokens(
        f'''template <typename Linalg> linalg::Matrix<Linalg,{R}U,{C}U> {NAME}({PARAMETERS}) {{
        using value_type = typename Linalg::value_type;
        linalg::Matrix<Linalg,{R}U,{C}U> result;
        // BEGIN GENERATED DAG
'''
    )
    SUFFIX = tokens('// END GENERATED DAG\nreturn result; }')
    require(
        SOURCE[: len(PREFIX)] == PREFIX and SOURCE[-len(SUFFIX) :] == SUFFIX,
        'invalid function envelope',
    )
    BODY = SOURCE[len(PREFIX) : -len(SUFFIX)]
    require(BODY and BODY[-1] == ';', 'incomplete statements')
    DIMENSIONS = {**SPEC['dimensions'], 'result': SPEC['shape']}
    DEFINED, OUTPUTS, PROGRAM = set(), set(), []
    START = 0
    for END, TOKEN in enumerate(BODY):
        if TOKEN != ';':
            continue
        LINE = ' '.join(BODY[START : END + 1])
        START = END + 1
        MATCH = re.fullmatch(
            r'(?:value_type const ([a-z][a-z0-9_]*)|result \( (\d+)U , (\d+)U \)) = (.*) ;', LINE
        )
        require(MATCH is not None, 'invalid statement')
        TARGET = MATCH[1] if MATCH[1] else ('out', int(MATCH[2]), int(MATCH[3]))
        require(TARGET not in DEFINED, 'duplicate assignment')
        CHECK = re.sub(r'\b(?:' + '|'.join(DIMENSIONS) + r') \( \d+U , \d+U \)', '@', MATCH[4])
        CHECK = re.sub(r'value_type \{ (- )?[012] \}', '@', CHECK)
        require(re.search(r'(?<![\w])\d', CHECK) is None, 'untyped literal')
        EXPR = re.sub(r'value_type \{ (- )?(\d+) \}', r'(\1\2)', MATCH[4])
        EXPR = re.sub(r'\b(\d+)U\b', r'\1', EXPR)
        NODE = expression(ast.parse(EXPR, mode='eval').body, DIMENSIONS)
        for REF in references(NODE):
            if isinstance(REF, str) or REF[0] == 'out':
                require(REF in DEFINED, 'use before definition')
        if isinstance(TARGET, tuple):
            _, I, J = TARGET
            require(0 <= I < R and 0 <= J < C, 'invalid output access')
            if SPEC['mirror'] and I > J:
                require(
                    all(('out', A, B) in OUTPUTS for A in range(R) for B in range(A, C)),
                    'mirror before upper triangle',
                )
                require(NODE == ('ref', ('out', J, I)), 'invalid mirror')
            OUTPUTS.add(TARGET)
        else:
            require(not OUTPUTS, 'temporary after output')
        DEFINED.add(TARGET)
        PROGRAM.append((TARGET, NODE))
    require(OUTPUTS == {('out', I, J) for I in range(R) for J in range(C)}, 'incomplete matrix')
    return PROGRAM


def parse_header(TEXT, GROUP):
    SOURCE, PREFIX, SUFFIX = tokens(TEXT), tokens(PREAMBLE), tokens(FOOTER)
    require(
        SOURCE[: len(PREFIX)] == PREFIX and SOURCE[-len(SUFFIX) :] == SUFFIX,
        'invalid header envelope',
    )
    BODY = SOURCE[len(PREFIX) : -len(SUFFIX)]
    STARTS = [I for I, T in enumerate(BODY) if T == 'template']
    require(STARTS and STARTS[0] == 0, 'invalid function sequence')
    STARTS.append(len(BODY))
    EXPECTED = {N: S for N, S in contracts().items() if S['group'] == GROUP}
    RESULT = {}
    for START, END in zip(STARTS, STARTS[1:]):
        SEGMENT = BODY[START:END]
        NAMES = [T for T in SEGMENT[:30] if T.startswith('ins_')]
        require(len(NAMES) == 1 and NAMES[0] in EXPECTED, 'unknown function')
        NAME = NAMES[0]
        require(NAME not in RESULT, 'duplicate function')
        RESULT[NAME] = parse_function(SEGMENT, NAME, EXPECTED[NAME])
    require(RESULT.keys() == EXPECTED.keys(), 'missing function')
    return RESULT


def verify(PROGRAM, SPEC):
    VALUES, REFERENCE = model(SPEC)
    for TARGET, NODE in PROGRAM:
        VALUES[TARGET] = S.expand(symbolic_expression(NODE, VALUES))
    for I in range(REFERENCE.rows):
        for J in range(REFERENCE.cols):
            require(
                S.expand(VALUES['out', I, J] - REFERENCE[I, J]) == 0,
                f'identity mismatch at {I},{J}',
            )
    return REFERENCE.rows * REFERENCE.cols
